//   96..99   cloudShadowHiFi      (enable, absorption, strength, _pad)
//   100..115 cloudShadowSunViewVP (mat4 — world ECEF → sun ortho clip)
// When `enable` (offset 96) < 0.5 the scattering kernel's `sampleCloudShadow`
