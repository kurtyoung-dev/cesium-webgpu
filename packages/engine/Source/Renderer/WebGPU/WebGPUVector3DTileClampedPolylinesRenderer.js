const BYTES_PER_BATCH_COLOR = 16;
const INITIAL_BATCH_BUFFER_FEATURES = 64;

const VERTEX_STRIDE_FLOATS = 24;
const VERTEX_STRIDE_BYTES = VERTEX_STRIDE_FLOATS * 4;

