function buildClampedPolylinePipelineResources(device, format, depthFormat) {
  const code = `
struct U {
  modifiedView: mat4x4<f32>,
  projection: mat4x4<f32>,
  invProjection: mat4x4<f32>,
  normalCol0: vec4<f32>,
  normalCol1: vec4<f32>,
  normalCol2: vec4<f32>,
  viewport: vec4<f32>,
  minMaxHeights: vec2<f32>,
  pixelRatio: f32,
  _pad: f32,
};
@group(0) @binding(0) var<uniform> u: U;
@group(0) @binding(1) var<storage, read> batchColors: array<vec4<f32>>;

@group(1) @binding(0) var globeDepthTex: texture_2d<f32>;
@group(1) @binding(1) var depthSampler: sampler;

struct VOut {
  @builtin(position) pos: vec4<f32>,
  @location(0) startPlaneEC: vec4<f32>,
  @location(1) endPlaneEC: vec4<f32>,
  @location(2) rightPlaneEC: vec4<f32>,
  @location(3) volumeUpEC_halfWidth: vec4<f32>,
  @location(4) col: vec4<f32>,
};

fn applyNormal(v: vec3<f32>) -> vec3<f32> {
  let m = mat3x3<f32>(u.normalCol0.xyz, u.normalCol1.xyz, u.normalCol2.xyz);
  return m * v;
}

// czm_metersPerPixel(positionEC) approximation. Pulled from the GroundPolyline
// FR: proj[0][0] / proj[1][1] are 1/(aspect*tan(fov/2)) and 1/tan(fov/2);
// 2/W and 2/H over those give the NDC-pixel size.
fn metersPerPixel(positionEC: vec3<f32>) -> f32 {
  let pixelW = 2.0 / (u.viewport.z * u.projection[0][0]);
  let pixelH = 2.0 / (u.viewport.w * u.projection[1][1]);
  let pixelSize = max(abs(pixelW), abs(pixelH));
  return pixelSize * abs(positionEC.z);
}

@vertex
fn vsMain(
  @location(0) startEN: vec3<f32>,
  @location(6) batchId: f32,
  @location(1) endEN: vec3<f32>,
  @location(2) startPosH: vec4<f32>,
  @location(3) endPosH: vec4<f32>,
  @location(4) startFaceNVC: vec4<f32>,
  @location(5) endFaceNHW: vec4<f32>,
) -> VOut {
  // vertex corner IDs follow the WebGL VS exactly:
  //   isEnd = floor(corner * 0.251)         -> 0 for start, 1 for end face
  //   isTop = floor(corner * mix(0.51, 0.19, isEnd))
  //                                          -> 0 for bottom, 1 for top
  let cornerId = startFaceNVC.w;
  let isEnd = floor(cornerId * 0.251);
  let isTop = floor(cornerId * mix(0.51, 0.19, isEnd));

  let forward = endPosH.xyz - startPosH.xyz;
  var right = normalize(cross(forward, startEN));

  var posObj = vec4<f32>(startPosH.xyz + forward * isEnd, 1.0);

  let volumeUpEC = applyNormal(normalize(cross(right, forward)));

  // Vertical extrusion to bracket the global terrain min/max height.
  let normalForExtrude = mix(startEN, endEN, isEnd);
  var heightOffset = mix(startPosH.w, endPosH.w, isEnd);
  heightOffset = mix(u.minMaxHeights.y, u.minMaxHeights.x, isTop) - heightOffset;
  posObj = vec4<f32>(posObj.xyz + heightOffset * normalForExtrude, 1.0);

  // RTC -> EC.
  var posEC = u.modifiedView * posObj;
  let rightEC = applyNormal(right);

  // Width miter push. Mirrors VectorClampedPolylineVS:
  //   N = (vertexCorner < 4 ? -startFaceNormal : endFaceNormal) ⊗ ellipsoidNormal
  //   miterPushNormal = czm_normal * normalize(N)
  //   distance = widthEC / dot(miterPushNormal, right)
  //   sign     = sign(0.5 - mod(corner, 2.0))
  var scratchNormal = mix(-startFaceNVC.xyz, endFaceNHW.xyz, isEnd);
  scratchNormal = cross(scratchNormal, mix(startEN, endEN, isEnd));
  let miterPushNormal = applyNormal(normalize(scratchNormal));

  let widthEC = 2.0 * endFaceNHW.w * max(0.0, metersPerPixel(posEC.xyz));
  let widthOffset = widthEC / dot(miterPushNormal, rightEC);
  let cornerMod2 = cornerId - 2.0 * floor(cornerId * 0.5);
  let signMod = sign(0.5 - cornerMod2);
  posEC = vec4<f32>(posEC.xyz + miterPushNormal * (widthOffset * signMod), 1.0);

  var clip = u.projection * posEC;
  // Manual depth clamp: WebGPU has no equivalent of WebGL's depthClamp
  // extension. Without this, fragments past the far plane (very common
  // for shadow volumes that bracket terrain min/max) are clipped and
  // the volume coverage thins out near the horizon. Clamping z to
  // [0, w] keeps the rasterized footprint at the far plane instead.
  clip.z = clamp(clip.z, 0.0, clip.w);

  // Side-plane reconstruction in eye-space, per the WebGL VS.
  let startEC = u.modifiedView * vec4<f32>(startPosH.xyz, 1.0);
  let endEC = u.modifiedView * vec4<f32>(endPosH.xyz, 1.0);
  let startNormalEC = applyNormal(startFaceNVC.xyz);
  let endNormalEC = applyNormal(endFaceNHW.xyz);

  var output: VOut;
  output.pos = clip;
  output.startPlaneEC = vec4<f32>(startNormalEC, -dot(startNormalEC, startEC.xyz));
  output.endPlaneEC = vec4<f32>(endNormalEC, -dot(endNormalEC, endEC.xyz));
  output.rightPlaneEC = vec4<f32>(rightEC, -dot(rightEC, startEC.xyz));
  output.volumeUpEC_halfWidth = vec4<f32>(volumeUpEC, endFaceNHW.w);
  output.col = batchColors[u32(batchId)];
  return output;
}

fn unpackDepth(packed: vec4<f32>) -> f32 {
  return dot(packed, vec4<f32>(1.0, 1.0 / 255.0, 1.0 / 65025.0, 1.0 / 16581375.0));
}

fn windowToEyeCoordinates(fragXY: vec2<f32>, depth: f32) -> vec3<f32> {
  // WebGPU NDC z is already in [0, 1] (no remap needed). Y flip
  // accounts for fragCoord (top-left origin) vs NDC (bottom-up).
  var ndc = (fragXY / u.viewport.zw) * 2.0 - 1.0;
  ndc.y = -ndc.y;
  let clip = vec4<f32>(ndc, depth, 1.0);
  let eye = u.invProjection * clip;
  return eye.xyz / eye.w;
}

fn planeDistance(plane: vec4<f32>, p: vec3<f32>) -> f32 {
  return dot(plane.xyz, p) + plane.w;
}

@fragment
fn fsMain(in: VOut) -> @location(0) vec4<f32> {
  // in.pos is delivered in framebuffer coordinates here (xy = pixels,
  // z = clip-space depth, w = 1/clipW). We sample the globe-depth
  // texture at this fragment's UV to get the surface depth, then
  // reconstruct the eye-space surface position and test it against
  // the per-instance polyline planes.
  let screenUV = in.pos.xy / u.viewport.zw;
  let packed = textureSampleLevel(globeDepthTex, depthSampler, screenUV, 0.0);
  let surfaceDepth = unpackDepth(packed);
  if (surfaceDepth == 0.0) {
    discard;
  }

  let eyeCoord = windowToEyeCoordinates(in.pos.xy, surfaceDepth);

  // Width threshold, broadened at grazing angles between the view
  // direction and the volume's up-axis. This matches the WebGL FS
  // which uses dot(-normalize(eyeCoord.xyz), v_volumeUpEC).
  let halfWidth = in.volumeUpEC_halfWidth.w;
  let volumeUpEC = in.volumeUpEC_halfWidth.xyz;
  var halfMaxWidth = halfWidth * metersPerPixel(eyeCoord);
  let viewDir = -normalize(eyeCoord);
  halfMaxWidth = halfMaxWidth + halfMaxWidth * (1.0 - dot(viewDir, volumeUpEC));

  let widthwiseDistance = planeDistance(in.rightPlaneEC, eyeCoord);
  let distFromStart = planeDistance(in.startPlaneEC, eyeCoord);
  let distFromEnd = planeDistance(in.endPlaneEC, eyeCoord);

  if (abs(widthwiseDistance) > halfMaxWidth || distFromStart < 0.0 || distFromEnd < 0.0) {
    discard;
  }
  return in.col;
}
`;

  const mod = device.createShaderModule({
    label: "Vector3DTileClampedPolylines",
    code,
  });

  const sharedBgl = makeBindGroupLayout(
    device,
    "Vector3DTileClampedPolylines Shared BGL",
    [
      uniformBuffer(0, Stage.VERTEX_FRAGMENT),
      storageBuffer(1, Stage.VERTEX_FRAGMENT, { readOnly: true }),
    ],
  );

  const depthSampleBgl = makeBindGroupLayout(
    device,
    "Vector3DTileClampedPolylines DepthSample BGL",
    [
      textureEntry(0, Stage.FRAGMENT, { sampleType: "float" }),
      samplerEntry(1, Stage.FRAGMENT, "filtering"),
    ],
  );

  const layout = device.createPipelineLayout({
    label: "Vector3DTileClampedPolylines PipelineLayout",
    bindGroupLayouts: [sharedBgl, depthSampleBgl],
  });

  // 96-byte interleaved layout. See VS argument order for shaderLocation
  // mapping. batchId sits at offset 12 to fill the 4-byte tail of the
  // first vec3 attribute and keep the next vec4 attributes vec4-aligned.
  const vertexBuffers = [
    {
      arrayStride: VERTEX_STRIDE_BYTES,
      attributes: [
        { shaderLocation: 0, offset: 0, format: "float32x3" },
        { shaderLocation: 6, offset: 12, format: "float32" },
        { shaderLocation: 1, offset: 16, format: "float32x3" },
        { shaderLocation: 2, offset: 32, format: "float32x4" },
        { shaderLocation: 3, offset: 48, format: "float32x4" },
        { shaderLocation: 4, offset: 64, format: "float32x4" },
        { shaderLocation: 5, offset: 80, format: "float32x4" },
      ],
    },
  ];

  const colorDescriptor = {
    name: `Vector3DTileClampedPolylines color [${format}/${depthFormat}]`,
    layout,
    vertex: { module: mod, entryPoint: "vsMain", buffers: vertexBuffers },
    fragment: {
      module: mod,
      entryPoint: "fsMain",
      targets: [
        {
          format,
          blend: {
            color: {
              srcFactor: "src-alpha",
              dstFactor: "one-minus-src-alpha",
              operation: "add",
            },
            alpha: {
              srcFactor: "one",
              dstFactor: "one-minus-src-alpha",
              operation: "add",
            },
          },
        },
      ],
    },
    // Cull FRONT — see Vector3DTileClampedPolylines.js::getRenderState
    // for the rationale (volumes are wound inside-out so the VS-driven
    // re-inversion makes the visible faces "outside"; back-face culling
    // would drop them).
    primitive: { topology: "triangle-list", cullMode: "front" },
    depthStencil: {
      format: depthFormat,
      depthWriteEnabled: false,
      // The volume must rasterize even where its z is past the depth
      // buffer. The classifier samples globe depth in the FS and decides
      // whether to draw, so the GPU's hardware depth test is bypassed
      // intentionally.
      depthCompare: "always",
    },
  };

  return { colorDescriptor, sharedBgl, depthSampleBgl };
}

function descriptorToGPU(d) {
  return {
    label: d.name,
    layout: d.layout ?? "auto",
    vertex: {
      module: d.vertex.module,
      entryPoint: d.vertex.entryPoint,
      buffers: d.vertex.buffers,
    },
    fragment: d.fragment
      ? {
          module: d.fragment.module,
          entryPoint: d.fragment.entryPoint,
          targets: d.fragment.targets,
        }
      : undefined,
    primitive: d.primitive,
    depthStencil: d.depthStencil,
    multisample: d.multisample,
  };
}

function tryResolvePipelines(device, pipelineCache, resources, cache) {
  if (cache.colorPipeline) {
    return true;
  }
  if (pipelineCache) {
    const sync = pipelineCache.getPipelineSync(resources.colorDescriptor);
    if (sync) {
      cache.colorPipeline = sync;
      cache.pipelineRequestPending = false;
      return true;
    }
    if (!cache.pipelineRequestPending) {
      cache.pipelineRequestPending = true;
      pipelineCache
        .getPipeline(resources.colorDescriptor)
        .then((p) => {
          cache.colorPipeline = p;
          cache.pipelineRequestPending = false;
        })
        .catch(() => {
          cache.pipelineRequestPending = false;
        });
    }
    return false;
  }
  cache.colorPipeline = device.createRenderPipeline(
    descriptorToGPU(resources.colorDescriptor),
  );
  return true;
}

const scratchModifiedView = new Matrix4();

function packUniforms(data, frameState, primitive) {
  const uniformState = frameState.context.uniformState;

  // u_modifiedModelView = view with translation set to view * center.
  // This matches the WebGL VS and keeps RTC precision intact.
  Matrix4.clone(uniformState.view, scratchModifiedView);
  const center = primitive._center;
  if (defined(center)) {
    const m = scratchModifiedView;
    const tx = m[0] * center.x + m[4] * center.y + m[8] * center.z + m[12];
    const ty = m[1] * center.x + m[5] * center.y + m[9] * center.z + m[13];
    const tz = m[2] * center.x + m[6] * center.y + m[10] * center.z + m[14];
    m[12] = tx;
    m[13] = ty;
    m[14] = tz;
  }
  Matrix4.pack(scratchModifiedView, data, 0);
  Matrix4.pack(uniformState.projection, data, 16);
  Matrix4.pack(uniformState.inverseProjection, data, 32);

  // czm_normal — Matrix3 stored column-major. Pack as 3 padded vec4
  // columns starting at float 48.
  const normal = uniformState.normal;
  data[48] = normal[0];
  data[49] = normal[1];
  data[50] = normal[2];
  data[51] = 0.0;
  data[52] = normal[3];
  data[53] = normal[4];
  data[54] = normal[5];
  data[55] = 0.0;
  data[56] = normal[6];
  data[57] = normal[7];
  data[58] = normal[8];
  data[59] = 0.0;

  const viewport = uniformState.viewportCartesian4 ?? uniformState.viewport;
  data[60] = viewport?.x ?? 0.0;
  data[61] = viewport?.y ?? 0.0;
  data[62] = viewport?.z ?? frameState.context.drawingBufferWidth ?? 0.0;
  data[63] = viewport?.w ?? frameState.context.drawingBufferHeight ?? 0.0;

  const mmh = primitive._minimumMaximumVectorHeights;
  data[64] = mmh?.x ?? 0.0;
  data[65] = mmh?.y ?? 0.0;
  data[66] = uniformState.pixelRatio ?? 1.0;
  data[67] = 0.0;
}

function ensureVertexBuffer(cache, primitive, device) {
  if (defined(cache.vertexGPUBuffer)) {
    return;
  }

  const startEN = primitive._startEllipsoidNormals;
  const endEN = primitive._endEllipsoidNormals;
  const startPosH = primitive._startPositionAndHeights;
  const endPosH = primitive._endPositionAndHeights;
  const startFaceNVC = primitive._startFaceNormalAndVertexCornerIds;
  const endFaceNHW = primitive._endFaceNormalAndHalfWidths;
  const vertexBatchIds = primitive._vertexBatchIds;
  if (
    !defined(startEN) ||
    !defined(endEN) ||
    !defined(startPosH) ||
    !defined(endPosH) ||
    !defined(startFaceNVC) ||
    !defined(endFaceNHW) ||
    !defined(vertexBatchIds)
  ) {
    return;
  }

  const numVerts = startEN.length / 3;
  if (numVerts === 0) {
    return;
  }

  const interleaved = new Float32Array(numVerts * VERTEX_STRIDE_FLOATS);
  for (let v = 0; v < numVerts; v++) {
    const dst = v * VERTEX_STRIDE_FLOATS;
    const s3 = v * 3;
    const s4 = v * 4;
    interleaved[dst] = startEN[s3];
    interleaved[dst + 1] = startEN[s3 + 1];
    interleaved[dst + 2] = startEN[s3 + 2];
    interleaved[dst + 3] = vertexBatchIds[v];
    interleaved[dst + 4] = endEN[s3];
    interleaved[dst + 5] = endEN[s3 + 1];
    interleaved[dst + 6] = endEN[s3 + 2];
    // dst + 7 padded by Float32Array zero init.
    interleaved[dst + 8] = startPosH[s4];
    interleaved[dst + 9] = startPosH[s4 + 1];
    interleaved[dst + 10] = startPosH[s4 + 2];
    interleaved[dst + 11] = startPosH[s4 + 3];
    interleaved[dst + 12] = endPosH[s4];
    interleaved[dst + 13] = endPosH[s4 + 1];
    interleaved[dst + 14] = endPosH[s4 + 2];
    interleaved[dst + 15] = endPosH[s4 + 3];
    interleaved[dst + 16] = startFaceNVC[s4];
    interleaved[dst + 17] = startFaceNVC[s4 + 1];
    interleaved[dst + 18] = startFaceNVC[s4 + 2];
    interleaved[dst + 19] = startFaceNVC[s4 + 3];
    interleaved[dst + 20] = endFaceNHW[s4];
    interleaved[dst + 21] = endFaceNHW[s4 + 1];
    interleaved[dst + 22] = endFaceNHW[s4 + 2];
    interleaved[dst + 23] = endFaceNHW[s4 + 3];
  }

  cache.vertexGPUBuffer = WebGPUBuffer.createVertexBuffer(
    device,
    interleaved,
    "Vector3DTileClampedPolylines VB",
  );
  cache.vertexCount = numVerts;
}

function ensureIndexBuffer(cache, primitive, device) {
  if (defined(cache.indexGPUBuffer)) {
    return;
  }
  const indices = primitive._indices;
  if (!defined(indices)) {
    return;
  }

  const needsU32 = indices.BYTES_PER_ELEMENT === 4;
  const typed = needsU32 ? new Uint32Array(indices) : new Uint16Array(indices);
  cache.indexFormat = needsU32 ? "uint32" : "uint16";
  cache.indexGPUBuffer = device.createBuffer({
    label: "Vector3DTileClampedPolylines IB",
    size: typed.byteLength,
    usage: GPUBufferUsage.INDEX | GPUBufferUsage.COPY_DST,
  });
  device.queue.writeBuffer(cache.indexGPUBuffer, 0, typed);
  cache.indexCount = indices.length;
}

function ensureBatchColorStorage(cache, primitive, device) {
  const featuresLength =
    primitive._batchTable?.featuresLength ??
    primitive._batchIds?.length ??
    INITIAL_BATCH_BUFFER_FEATURES;
  const requiredBytes = Math.max(
    featuresLength * BYTES_PER_BATCH_COLOR,
    INITIAL_BATCH_BUFFER_FEATURES * BYTES_PER_BATCH_COLOR,
  );

  if (
    defined(cache.batchColorBuffer) &&
    cache.batchColorBufferCapacity >= requiredBytes
  ) {
    return;
  }
  if (defined(cache.batchColorBuffer)) {
    cache.batchColorBuffer.destroy();
  }
  cache.batchColorBuffer = device.createBuffer({
    label: "Vector3DTileClampedPolylines batch colors",
    size: requiredBytes,
    usage: GPUBufferUsage.STORAGE | GPUBufferUsage.COPY_DST,
  });
  cache.batchColorBufferCapacity = requiredBytes;
  cache.batchColorScratch = new Float32Array(requiredBytes / 4);
  cache._sharedBindGroupDirty = true;
}

function uploadBatchColors(cache, primitive, device) {
  const scratch = cache.batchColorScratch;
  if (!defined(scratch)) {
    return;
  }

  // Default every feature to the primitive-level highlight color. The
  // batch-table style hook overrides per feature when applyStyle runs.
  const highlight = primitive._highlightColor;
  const r = highlight?.red ?? 1.0;
  const g = highlight?.green ?? 1.0;
  const b = highlight?.blue ?? 1.0;
  const a = highlight?.alpha ?? 1.0;
  for (let i = 0; i < scratch.length; i += 4) {
    scratch[i] = r;
    scratch[i + 1] = g;
    scratch[i + 2] = b;
    scratch[i + 3] = a;
  }

  device.queue.writeBuffer(
    cache.batchColorBuffer,
    0,
    scratch.buffer,
    scratch.byteOffset,
    cache.batchColorBufferCapacity,
  );
}

function createWebGPUVector3DTileClampedPolylineCommands(
  primitive,
  frameState,
) {
  const context = frameState.context;
  const device = context.device;

  if (!defined(primitive._webgpuCache)) {
    primitive._webgpuCache = {};
  }
  const cache = primitive._webgpuCache;

  const sceneGen = context._scenePipelineFormatGeneration ?? 0;
  if (
    defined(cache._pipelineResources) &&
    cache._pipelineFormatGeneration !== sceneGen
  ) {
    cache._pipelineResources = undefined;
    cache.colorPipeline = undefined;
    cache.sharedBindGroup = undefined;
    cache.depthSampleBindGroup = undefined;
  }
  if (!defined(cache._pipelineResources)) {
    const format = context.scenePipelineFormat || "bgra8unorm";
    const depthFmt = context.depthFormat || "depth24plus-stencil8";
    cache._pipelineResources = buildClampedPolylinePipelineResources(
      device,
      format,
      depthFmt,
    );
    cache._pipelineFormatGeneration = sceneGen;
    cache.pipelineRequestPending = false;
  }
  if (
    !tryResolvePipelines(
      device,
      context.webgpuPipelineCache ?? null,
      cache._pipelineResources,
      cache,
    )
  ) {
    return { colorCommands: [] };
  }

  if (!defined(cache.uniformBuffer)) {
    cache.uniformBuffer = WebGPUBuffer.createUniformBuffer(
      device,
      UNIFORM_BUFFER_SIZE,
      "Vector3DTileClampedPolylines uniforms",
    );
    cache.uniformData = new Float32Array(UNIFORM_BUFFER_SIZE / 4);
  }
  ensureBatchColorStorage(cache, primitive, device);
  if (cache._sharedBindGroupDirty || !defined(cache.sharedBindGroup)) {
    cache.sharedBindGroup = device.createBindGroup({
      label: "Vector3DTileClampedPolylines shared BG",
      layout: cache._pipelineResources.sharedBgl,
      entries: [
        { binding: 0, resource: { buffer: cache.uniformBuffer.buffer } },
        { binding: 1, resource: { buffer: cache.batchColorBuffer } },
      ],
    });
    cache._sharedBindGroupDirty = false;
  }

  ensureVertexBuffer(cache, primitive, device);
  ensureIndexBuffer(cache, primitive, device);
  if (!defined(cache.vertexGPUBuffer) || !defined(cache.indexGPUBuffer)) {
    return { colorCommands: [] };
  }

  packUniforms(cache.uniformData, frameState, primitive);
  device.queue.writeBuffer(
    cache.uniformBuffer.buffer,
    0,
    cache.uniformData.buffer,
    0,
    UNIFORM_BUFFER_SIZE,
  );

  if (!cache._batchColorsUploaded) {
    uploadBatchColors(cache, primitive, device);
    cache._batchColorsUploaded = true;
  }

  // Depth-source resolver. Mirrors WebGPUVector3DTilePrimitiveRenderer:
  // pick `_packedTranslucentDepthView` if present (covers both terrain
  // + 3D-Tile depth), else fall back to `_globeDepthView`.
  const packedTranslucentView = context._packedTranslucentDepthView ?? null;
  const globeDepthView = context._globeDepthView ?? null;
  const depthSourceView = packedTranslucentView ?? globeDepthView;
  if (!depthSourceView) {
    return { colorCommands: [] };
  }
  if (!defined(cache.depthSampleSampler)) {
    cache.depthSampleSampler = device.createSampler({
      label: "Vector3DTileClampedPolylines depth-sample sampler",
      magFilter: "linear",
      minFilter: "linear",
      addressModeU: "clamp-to-edge",
      addressModeV: "clamp-to-edge",
    });
  }
  if (
    !defined(cache.depthSampleBindGroup) ||
    cache.depthSampleViewRef !== depthSourceView
  ) {
    cache.depthSampleBindGroup = device.createBindGroup({
      label: "Vector3DTileClampedPolylines depth-sample BG",
      layout: cache._pipelineResources.depthSampleBgl,
      entries: [
        { binding: 0, resource: depthSourceView },
        { binding: 1, resource: cache.depthSampleSampler },
      ],
    });
    cache.depthSampleViewRef = depthSourceView;
  }
  const resolveDepthSampleBindGroup = () => {
    const currentSource =
      context._packedTranslucentDepthView ?? context._globeDepthView;
    if (!currentSource) {
      return null;
    }
    if (cache.depthSampleViewRef !== currentSource) {
      cache.depthSampleBindGroup = device.createBindGroup({
        label: "Vector3DTileClampedPolylines depth-sample BG",
        layout: cache._pipelineResources.depthSampleBgl,
        entries: [
          { binding: 0, resource: currentSource },
          { binding: 1, resource: cache.depthSampleSampler },
        ],
      });
      cache.depthSampleViewRef = currentSource;
    }
    return cache.depthSampleBindGroup;
  };

  // Pass routing — emit one command per pass the primitive should
  // appear in (TERRAIN, 3D-TILE, or both).
  const classType =
    primitive._classificationType ?? CLASSIFICATION_TYPE_TERRAIN;
  const colorCommands = [];
  const sharedDrawArgs = {
    pipeline: cache.colorPipeline,
    bindGroups: [cache.sharedBindGroup, cache.depthSampleBindGroup],
    bindGroupResolvers: [undefined, resolveDepthSampleBindGroup],
    vertexBuffers: [cache.vertexGPUBuffer],
    indexBuffer: cache.indexGPUBuffer,
    indexFormat: cache.indexFormat,
    indexCount: cache.indexCount || 0,
    vertexCount: 0,
    owner: primitive,
  };
  if (
    classType === CLASSIFICATION_TYPE_TERRAIN ||
    classType === CLASSIFICATION_TYPE_BOTH
  ) {
    colorCommands.push(
      new WebGPUDrawCommand({
        ...sharedDrawArgs,
        pass: PASS_TERRAIN_CLASSIFICATION,
      }),
    );
  }
  if (
    classType === CLASSIFICATION_TYPE_3DTILE ||
    classType === CLASSIFICATION_TYPE_BOTH
  ) {
    colorCommands.push(
      new WebGPUDrawCommand({
        ...sharedDrawArgs,
        pass: PASS_CESIUM_3D_TILE_CLASSIFICATION,
      }),
    );
  }

  return { colorCommands };
}

function destroyWebGPUVector3DTileClampedPolylineResources(primitive) {
  const cache = primitive._webgpuCache;
  if (!defined(cache)) {
    return;
  }
  if (defined(cache.uniformBuffer)) {
    cache.uniformBuffer.destroy();
  }
  if (defined(cache.batchColorBuffer)) {
    cache.batchColorBuffer.destroy();
  }
  if (defined(cache.vertexGPUBuffer)) {
    cache.vertexGPUBuffer.destroy();
  }
  if (defined(cache.indexGPUBuffer)) {
    cache.indexGPUBuffer.destroy();
  }
  primitive._webgpuCache = undefined;
}

