/**
 * @module WebGPUVector3DTileClampedPolylinesRenderer
 *
 * WebGPU equivalent of `Vector3DTileClampedPolylines` (3D Tiles polylines
 * clamped to terrain). Pairs with `WebGPUVector3DTilePolylinesRenderer`
 * for the un-clamped variant and with `WebGPUVector3DTilePrimitiveRenderer`
 * for the polygon classifier.
 *
 * Architecture mirrors `WebGPUGroundPolylineRenderer`'s depth-sample
 * classifier (ADR-2026-04-28). The volume's rasterization handles lateral
 * coverage; the FS samples the globe depth texture, reconstructs the eye-
 * space surface position, and tests it against three EC planes (start,
 * end, right) plus the per-fragment width threshold computed from
 * `czm_metersPerPixel`. Fragments outside the swept volume are discarded.
 *
 * The CPU side (worker-decoded `_startEllipsoidNormals`,
 * `_endEllipsoidNormals`, `_startPositionAndHeights`,
 * `_endPositionAndHeights`, `_startFaceNormalAndVertexCornerIds`,
 * `_endFaceNormalAndHalfWidths`, `_vertexBatchIds`, `_indices`) is
 * generated by the existing `createVectorTileClampedPolylines` task
 * processor. On the WebGPU path, `Vector3DTileClampedPolylines.update()`
 * keeps those arrays alive (the WebGL `finishVertexArray` is skipped) so
 * this renderer can upload them straight into GPU buffers.
 *
 * **Shipped (Batch 114):**
 *   - WGSL VS port of `Vector3DTileClampedPolylinesVS.glsl` — per-vertex
 *     shadow-volume extrusion (height + width miter), eye-space plane
 *     reconstruction, manual depth clamp.
 *   - WGSL FS port of `Vector3DTileClampedPolylinesFS.glsl` — depth-
 *     sampled classifier with 5-plane test (right ± halfMaxWidth, start/
 *     end half-spaces, sky discard).
 *   - 7-attribute interleaved vertex layout in a single 96-byte stream.
 *   - Per-batch color via storage buffer indexed by `batchId`.
 *   - Single shared depth-sample bind group reused across both ground
 *     passes (TERRAIN + 3D-TILE classification — see "Pass routing" below).
 *
 * **Deferred:**
 *   - Per-feature pick. Same trade-off as the polygon FR: the storage-
 *     buffer indirection means adding `pickColors[batchId]` is one extra
 *     `vec4[]` slot when a future batch enables it.
 *   - `DEBUG_SHOW_VOLUME` mode (visualizes the swept volume in red/blue).
 *   - Distinct depth source per pass: WebGL stencils against
 *     `czm_globeDepthTexture` for TERRAIN and against `czm_pickDepthTexture`
 *     for 3D-Tile classification. The current depth-sample resolver
 *     follows the same simplification as `WebGPUVector3DTilePrimitiveRenderer`
 *     — pick `_packedTranslucentDepthView` if present, else `_globeDepthView`.
 *
 * **Pass routing:**
 *
 *   `classificationType` is one of TERRAIN (0) / CESIUM_3D_TILE (1) /
 *   BOTH (2). The WebGPU command list dispatches a single command per
 *   pass it should appear in:
 *     - TERRAIN: `Pass.TERRAIN_CLASSIFICATION` (3)
 *     - CESIUM_3D_TILE: `Pass.CESIUM_3D_TILE_CLASSIFICATION` (6)
 *     - BOTH: emit one of each.
 *   Both commands share the same pipeline / bind groups / vertex+index
 *   buffer; only the pass enum differs.
 *
 * @private
 */
