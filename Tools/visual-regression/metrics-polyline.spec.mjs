/** An opaque black frame. */
function blank(width, height) {
  const data = new Uint8Array(width * height * 4);
  for (let i = 3; i < data.length; i += 4) {
    data[i] = 255;
  }
  return { width, height, data };
}

function put(image, x, y, [r, g, b]) {
  const i = (y * image.width + x) * 4;
  image.data[i] = r;
  image.data[i + 1] = g;
  image.data[i + 2] = b;
}

function fill(image, x0, y0, x1, y1, rgb) {
  for (let y = y0; y <= y1; y++) {
    for (let x = x0; x <= x1; x++) {
      put(image, x, y, rgb);
    }
  }
}

/** Every threshold the family uses, with its two neighbours. */
const BOUNDARY_VALUES = [
  0, 9, 10, 11, 19, 20, 21, 29, 30, 31, 39, 40, 41, 79, 80, 81, 89, 90, 91, 109,
  110, 111, 119, 120, 121, 139, 140, 141, 149, 150, 151, 179, 180, 181, 199,
  200, 201, 254, 255,
];

/** Deterministic LCG, so a failing frame can be regenerated by its seed. */
function rng(seed) {
  let state = seed >>> 0;
  return () => {
    state = (Math.imul(state, 1664525) + 1013904223) >>> 0;
    return state / 2 ** 32;
  };
}

function boundaryNoise(seed, width = 48, height = 40) {
  const next = rng(seed);
  const image = blank(width, height);
  const pick = () =>
    BOUNDARY_VALUES[Math.floor(next() * BOUNDARY_VALUES.length)];
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      put(image, x, y, [pick(), pick(), pick()]);
    }
  }
  return image;
}

/**
 * The five-material scene, drawn: a solid red band, a dashed cyan band, a
 * yellow glow with a linear profile, a magenta arrow (shaft + tapering head),
 * a lime core bracketed by blue outline rows, and a grey-white block.
 */
function linesFrame() {
  const image = blank(160, 64);
  fill(image, 10, 4, 150, 7, [255, 0, 0]);
  for (let x = 10; x <= 150; x++) {
    if ((x - 10) % 18 < 12) {
      fill(image, x, 12, x, 15, [0, 255, 255]);
    }
  }
  for (let y = 19; y <= 31; y++) {
    const v = Math.max(0, 255 - 40 * Math.abs(y - 25));
    fill(image, 10, y, 150, y, [v, v, 0]);
  }
  fill(image, 10, 36, 120, 41, [255, 0, 255]);
  for (let k = 0; k < 12; k++) {
    const half = 12 - k;
    fill(image, 121 + k, 39 - half, 121 + k, 38 + half, [255, 0, 255]);
  }
  fill(image, 10, 47, 150, 49, [0, 0, 255]);
  fill(image, 10, 50, 150, 53, [0, 255, 0]);
  fill(image, 10, 54, 150, 56, [0, 0, 255]);
  fill(image, 0, 58, 8, 62, [200, 200, 210]);
  return image;
}

/** A cyan arc bowing above a red chord, over boundary noise in one corner. */
function arcFrame(bow = 25) {
  const image = blank(120, 60);
  for (let x = 10; x <= 110; x++) {
    const t = (x - 60) / 50;
    const y = 40 - Math.round(bow * (1 - t * t));
    fill(image, x, y, x, y + 1, [0, 255, 255]);
    fill(image, x, 45, x, 46, [255, 0, 0]);
  }
  const noise = boundaryNoise(7, 8, 8);
  for (let y = 0; y < 8; y++) {
    for (let x = 0; x < 8; x++) {
      const i = (y * 8 + x) * 4;
      put(image, 112 + x, 52 + y, [...noise.data.slice(i, i + 3)]);
    }
  }
  return image;
}

/** A cyan block large enough to sample every 200th pixel more than once. */
function cyanBlock() {
  const image = blank(64, 48);
  fill(image, 4, 4, 59, 19, [0, 255, 255]);
  fill(image, 30, 25, 40, 30, [0, 230, 240]);
  return image;
}

/** The split texture on screen: red then blue along a horizontal band. */
function splitFrame() {
  const image = blank(100, 30);
  fill(image, 10, 10, 49, 19, [255, 0, 0]);
  fill(image, 50, 10, 89, 19, [0, 0, 255]);
  return image;
}

function fragmentFrame() {
  const image = blank(60, 30);
  fill(image, 20, 10, 29, 11, [0, 255, 255]);
  return image;
}

