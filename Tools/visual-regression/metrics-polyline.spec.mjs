/** A shaft of height 4 over 40 columns, then a head of the given heights. */
function arrowFrame(head) {
  const image = blank(60, 30);
  fill(image, 2, 13, 41, 16, [255, 0, 255]);
  head.forEach((height, k) => {
    const top = 15 - Math.floor(height / 2);
    fill(image, 42 + k, top, 42 + k, top + height - 1, [255, 0, 255]);
  });
  return image;
}

test("B9 arrowHeadProfile separates a triangular head from a rectangular one of the same box", () => {
  const magenta = channelThresholds({ rAbove: 30, gBelow: 30, bAbove: 30 });
  // Triangle: heights 12, 10, 8, 6, 4, 2 after a body of 4 (flare 6): the head
  // starts at the 12 and runs to the tip, sum 42 over peak 12 x 6 columns.
  const triangle = arrowHeadProfile(arrowFrame([12, 10, 8, 6, 4, 2]), magenta);
  assert.equal(triangle.body, 4);
  assert.equal(triangle.headColumns, 6);
  assert.equal(triangle.headPeak, 12);
  assert.equal(triangle.headFill, 42 / 72);
  // Rectangle: six columns of 12 — same box, fill 1.
  const rectangle = arrowHeadProfile(
    arrowFrame([12, 12, 12, 12, 12, 12]),
    magenta,
  );
  assert.equal(rectangle.headFill, 1);
  // No column flares past 1.5x the shaft: no head at all.
  assert.deepEqual(arrowHeadProfile(arrowFrame([5, 5]), magenta), {
    body: 4,
    headColumns: 0,
    headPeak: 0,
    headFill: null,
    head: [],
  });
  assert.equal(arrowHeadProfile(blank(4, 4), magenta), null);
  // The shaft is the median over the leading 80 % of the span, and the
  // columns between 70 % and 80 % decide it here. Over 20 columns whose
  // heights are eight 2s, nine 4s, then 10, 7, 3, the leading 80 % (columns
  // 0-16) holds eight 2s and nine 4s, so the median shaft is 4, the flare
  // bar is 6 and the head is columns 17-19 (sum 20 over peak 10 x 3). A 70 %
  // split (columns 0-14) would hold eight 2s and seven 4s, put the shaft at 2
  // and run the head back to column 8.
  const split = blank(24, 20);
  [2, 2, 2, 2, 2, 2, 2, 2, 4, 4, 4, 4, 4, 4, 4, 4, 4, 10, 7, 3].forEach(
    (height, x) => {
      const top = 10 - Math.floor(height / 2);
      fill(split, x, top, x, top + height - 1, [255, 0, 255]);
    },
  );
  const shaft = arrowHeadProfile(split, magenta);
  assert.equal(shaft.body, 4);
  assert.equal(shaft.headStart, 17);
  assert.equal(shaft.headColumns, 3);
  assert.equal(shaft.headFill, 20 / 30);
});

