test("B7 rowRunProfile: runs per row tell dash from solid, FWHM counts the rows at half the peak", () => {
  const image = blank(7, 3);
  // Row 0: XX.XX.X — three runs of a 200-bright class; row 1: XXXXXXX — one
  // run; row 2 empty.
  for (const x of [0, 1, 3, 4, 6]) put(image, x, 0, [200, 0, 0]);
  for (let x = 0; x < 7; x++) put(image, x, 1, [200, 0, 0]);
  const profile = rowRunProfile(image, anyChannelAbove(30));
  // colored 5 + 7, runs 3 + 1 over 2 colored rows; row sums 1000 and 1400,
  // half the peak is 700, so both rows count toward the FWHM.
  assert.deepEqual(profile, {
    colored: 12,
    runs: 4,
    coloredRows: 2,
    fwhm: 2,
    runsPerRow: 2,
  });
  assert.deepEqual(rowRunProfile(blank(3, 3), anyChannelAbove(30)), {
    colored: 0,
    runs: 0,
    coloredRows: 0,
    fwhm: 0,
    runsPerRow: 0,
  });
  // A row exactly AT half the peak counts. Rows of 4, 2 and 1 pixels at 200
  // sum to 800, 400 and 200; half the peak is exactly 400, so rows 0 and 1
  // count and row 2 does not. A strict `>` would count row 0 alone.
  const atHalf = blank(4, 3);
  fill(atHalf, 0, 0, 3, 0, [200, 0, 0]);
  fill(atHalf, 0, 1, 1, 1, [200, 0, 0]);
  put(atHalf, 0, 2, [200, 0, 0]);
  assert.equal(rowRunProfile(atHalf, anyChannelAbove(30)).fwhm, 2);
});

