#!/usr/bin/env node
// Probe (NEW-ORBITAL-SGP4-KERNEL verify — the headline accuracy feature):
// @purpose Verifies GPU df64 near-earth SGP4 kernel against embedded python-sgp4 vectors (<2 km/day); deep-space TLEs must be flagged and skipped
// @status ACTIVE
//
// a GPU df64 near-earth SGP4 kernel, riding the engine's feature-agnostic
// ComputeInstanceCollection scaffold, must propagate REAL near-earth TLEs and
// match python-sgp4 reference vectors within a documented position-accuracy
// budget — and a deep-space TLE must be correctly FLAGGED & SKIPPED, never
// silently propagated wrong.
//
// Architecture (matches the SGP4 stage guardrails):
//   - CPU FP64 PRE-CONDITIONING: sgp4init() (sgp4-reference.mjs) parses each
//     TLE and computes every time-INDEPENDENT SGP4 constant in FP64. The
//     constants are uploaded as the per-instance params (the precision-
//     critical secular rates as df64 hi/lo pairs). The JS FP64 sgp4()
//     reference is bit-validated against python-sgp4 separately
//     (validate-sgp4.mjs: 0.0000 m).
//   - GPU does ONLY the time-dependent update (SGP4_KERNEL_WGSL,
//     sgp4-kernel.mjs) in df64, composed with the SHIPPED scaffold WGSL
//     exactly like WebGPUComputeInstanceRenderer.
//   - NEAR-EARTH ONLY: sgp4init flags period >= 225 min as deep space; the
//     demo/probe SKIPS those (the kernel never sees them).
//
// Reference vectors are EMBEDDED (generated by python-sgp4 2.25, WGS-72),
// so the probe is self-contained — no python at probe-run time.
//
// Asserts:
//   (A) GPU ECEF position matches python-sgp4 (via the validated JS FP64
//       TEME->ECEF) within BUDGET_M for every near-earth sat at every sample
//       time across a full DAY of propagation.
//   (B) The deep-space GPS sat is flagged isDeepSpace by sgp4init and is NOT
//       in the uploaded set (skipped, not silently wrong).
//   (C) Zero WebGPU validation / console errors.
//
// Position-accuracy budget: < 2 km over a full day for near-earth SGP4. df64
// pre-conditioning gets WELL under that (reported). This is the documented
// budget — SGP4 itself is a ~1 km-class model; the GPU df64 port adds only
// sub-meter numerical drift on top of the algorithm's own truncation.
//
// Usage: node Tools/visual-regression/probe-orbital-sgp4.mjs
// Env:   PROBE_BASE (default http://localhost:8134)

import { chromium } from "playwright";
import { sgp4init, gstime, temeToEcef } from "./sgp4-reference.mjs";
import {
  SGP4_FLOATS_PER_INSTANCE,
  SGP4_KERNEL_WGSL,
  packSgp4Instance,
} from "./sgp4-kernel.mjs";

const BASE = process.env.PROBE_BASE || "http://localhost:8134";
const BUDGET_M = 2000.0; // < 2 km over a full day for near-earth SGP4

// ── Embedded python-sgp4 2.25 (WGS-72) reference vectors (TEME km) ──
const REF = [
  {
    name: "ISS",
    l1: "1 25544U 98067A   24001.50000000  .00016717  00000-0  10270-3 0  9999",
    l2: "2 25544  51.6416 247.4627 0006703 130.5360 325.0288 15.50125623 18883",
    deep: false,
    teme_km: [
      [0.0, 4122.463958, -1003.017667, 5293.18891],
      [90.0, 3611.727604, -2226.108676, 5293.986847],
      [360.0, 1312.190261, -5199.298586, 4163.040808],
      [720.0, -2351.940404, -6339.294785, 693.687527],
      [1440.0, -4224.34001, 899.523998, -5255.84949],
    ],
  },
  {
    name: "NOAA19",
    l1: "1 33591U 09005A   24001.45833333  .00000089  00000-0  72940-4 0  9991",
    l2: "2 33591  99.1888  10.2222 0013570 200.5556 159.5000 14.12501077767777",
    deep: false,
    teme_km: [
      [0.0, 7126.081121, 1285.178989, -0.875135],
      [90.0, 5133.165439, 1722.291169, -4806.43345],
      [360.0, -7018.487532, -1080.179754, -1323.659528],
      [720.0, 6714.931974, 850.26343, 2566.007422],
      [1440.0, 5415.026801, 286.503741, 4788.876004],
    ],
  },
  {
    name: "STARLINK",
    l1: "1 44713U 19074A   24001.50000000  .00002182  00000-0  15211-3 0  9994",
    l2: "2 44713  53.0533  92.9000 0001434  90.0000 270.0000 15.06398804230000",
    deep: false,
    teme_km: [
      [0.0, -342.044469, 6917.783565, -11.140597],
      [90.0, 1194.728894, 6530.443467, -1982.320042],
      [360.0, 4114.870641, 912.317436, -5502.400629],
      [720.0, 1023.818999, -6735.126051, -1258.002291],
      [1440.0, -1648.035005, 6273.105433, 2420.258965],
    ],
  },
  {
    name: "GPS",
    l1: "1 24876U 97035A   24001.00000000 -.00000027  00000-0  00000-0 0  9999",
    l2: "2 24876  55.4000 100.0000 0100000 200.0000 160.0000  2.00561000 99999",
    deep: true, // MEO ~12h period -> deep space; MUST be flagged + skipped
    teme_km: [],
  },
];

// ── Build the near-earth catalog: CPU FP64 pre-conditioning + df64 packing ──
const satrecs = [];
const skipped = [];
for (const sat of REF) {
  const s = sgp4init(sat.l1, sat.l2);
  if (s.isDeepSpace) {
    skipped.push({ name: sat.name, periodMin: s.periodMin });
    continue;
  }
  satrecs.push({ name: sat.name, ref: sat, s });
}

// The flat param buffer (one near-earth object per sample is overkill; we
// upload ONE instance per near-earth sat and dispatch once per sample time —
// simplest exact check). Build per-sample param arrays.
const SAMPLE_TIMES = [0.0, 90.0, 360.0, 720.0, 1440.0]; // minutes

// Reference ECEF (meters) per (sat, sample) via the VALIDATED JS path:
// python-sgp4 TEME -> ECEF with gstime at (epoch + t). This is the trusted
// answer the GPU ECEF must match.
function refEcef(sat, s, tmin) {
  const rec = sat.teme_km.find((r) => r[0] === tmin);
  const teme = [rec[1], rec[2], rec[3]];
  const gmst = gstime(s.jd + s.jdFrac + tmin / 1440.0);
  return temeToEcef(teme, gmst);
}

const browser = await chromium.launch({
  channel: "msedge",
  headless: true,
  args: ["--enable-unsafe-webgpu"],
});
const page = await browser.newPage();
const errors = [];
page.on("console", (m) => {
  if (m.type() === "error") errors.push(m.text());
});
page.on("pageerror", (e) => errors.push(`pageerror: ${e.message}`));
await page.goto(`${BASE}/Apps/CesiumViewer/index.html?renderer=webgpu`, {
  waitUntil: "domcontentloaded",
});

// Flat params for ALL near-earth sats, dispatched ONCE per sample time
// (each sat is instance i; `time` is the sample minutes). Color/pixelSize
// are placeholders (the probe checks position only).
const params = [];
for (const sr of satrecs) {
  params.push(...packSgp4Instance(sr.s, [1.0, 1.0, 1.0], 3.0));
}
const instanceCount = satrecs.length;

const gpu = await page.evaluate(
  async ({ base, params, instanceCount, fpi, kernel, sampleTimes }) => {
    const scaffoldResp = await fetch(
      `${base}/packages/engine/Source/Shaders/WebGPU/Compute/ComputeInstanceScaffold.wgsl`,
    );
    if (!scaffoldResp.ok) {
      return { error: `scaffold fetch ${scaffoldResp.status}` };
    }
    const scaffold = await scaffoldResp.text();
    const prologue = `const FLOATS_PER_INSTANCE: u32 = ${fpi >>> 0}u;\n\n`;
    const code = prologue + scaffold + "\n// kernel\n" + kernel + "\n";

    const adapter = await navigator.gpu.requestAdapter();
    if (!adapter) return { error: "no adapter" };
    const device = await adapter.requestDevice();
    const validationErrors = [];
    device.addEventListener("uncapturederror", (ev) => {
      validationErrors.push(String(ev.error?.message ?? ev.error));
    });

    device.pushErrorScope("validation");
    const module = device.createShaderModule({ code });
    const info = await module.getCompilationInfo();
    const compileMsgs = info.messages
      .filter((m) => m.type === "error")
      .map((m) => `${m.lineNum}:${m.linePos} ${m.message}`);

    const INSTANCE_RECORD_BYTES = 64;
    const paramsArr = new Float32Array(params);
    const paramsBuf = device.createBuffer({
      size: Math.max(paramsArr.byteLength, 4),
      usage: GPUBufferUsage.STORAGE | GPUBufferUsage.COPY_DST,
    });
    device.queue.writeBuffer(paramsBuf, 0, paramsArr);

    const recordsBuf = device.createBuffer({
      size: instanceCount * INSTANCE_RECORD_BYTES,
      usage: GPUBufferUsage.STORAGE | GPUBufferUsage.COPY_SRC,
    });
    const frameBuf = device.createBuffer({
      size: 16,
      usage: GPUBufferUsage.UNIFORM | GPUBufferUsage.COPY_DST,
    });

    const bgl = device.createBindGroupLayout({
      entries: [
        {
          binding: 0,
          visibility: GPUShaderStage.COMPUTE,
          buffer: { type: "read-only-storage" },
        },
        {
          binding: 1,
          visibility: GPUShaderStage.COMPUTE,
          buffer: { type: "storage" },
        },
        {
          binding: 2,
          visibility: GPUShaderStage.COMPUTE,
          buffer: { type: "uniform" },
        },
      ],
    });
    const pipeline = device.createComputePipeline({
      layout: device.createPipelineLayout({ bindGroupLayouts: [bgl] }),
      compute: { module, entryPoint: "computeInstanceMain" },
    });
    const bindGroup = device.createBindGroup({
      layout: bgl,
      entries: [
        { binding: 0, resource: { buffer: paramsBuf } },
        { binding: 1, resource: { buffer: recordsBuf } },
        { binding: 2, resource: { buffer: frameBuf } },
      ],
    });

    // Run the kernel once per sample time, reading back the ECEF positions.
    const perTime = {};
    for (const tmin of sampleTimes) {
      const frameData = new ArrayBuffer(16);
      // The engine (and the shared kernel) take `time` in SECONDS since epoch;
      // SGP4 works in minutes (the kernel divides by 60). Feed seconds here so
      // the probe exercises the exact same contract the demo does.
      new Float32Array(frameData)[0] = tmin * 60.0;
      new Uint32Array(frameData)[1] = instanceCount;
      device.queue.writeBuffer(frameBuf, 0, frameData);

      const readbackBuf = device.createBuffer({
        size: instanceCount * INSTANCE_RECORD_BYTES,
        usage: GPUBufferUsage.COPY_DST | GPUBufferUsage.MAP_READ,
      });
      const enc = device.createCommandEncoder();
      const pass = enc.beginComputePass();
      pass.setPipeline(pipeline);
      pass.setBindGroup(0, bindGroup);
      pass.dispatchWorkgroups(Math.ceil(instanceCount / 64));
      pass.end();
      enc.copyBufferToBuffer(
        recordsBuf,
        0,
        readbackBuf,
        0,
        instanceCount * INSTANCE_RECORD_BYTES,
      );
      device.queue.submit([enc.finish()]);
      await readbackBuf.mapAsync(GPUMapMode.READ);
      const view = new Float32Array(readbackBuf.getMappedRange().slice(0));
      readbackBuf.unmap();
      readbackBuf.destroy();

      const positions = [];
      for (let i = 0; i < instanceCount; i++) {
        const o = i * 16;
        positions.push([
          view[o + 0] + view[o + 4],
          view[o + 1] + view[o + 5],
          view[o + 2] + view[o + 6],
        ]);
      }
      perTime[tmin] = positions;
    }
    const scopeErr = await device.popErrorScope();

    paramsBuf.destroy();
    recordsBuf.destroy();
    frameBuf.destroy();
    return {
      perTime,
      compileMsgs,
      scopeErr: scopeErr ? String(scopeErr.message) : null,
      validationErrors,
    };
  },
  {
    base: BASE,
    params,
    instanceCount,
    fpi: SGP4_FLOATS_PER_INSTANCE,
    kernel: SGP4_KERNEL_WGSL,
    sampleTimes: SAMPLE_TIMES,
  },
);

if (gpu.error) {
  console.log(`SETUP FAIL: ${gpu.error}`);
  await browser.close();
  process.exit(1);
}
if (gpu.compileMsgs && gpu.compileMsgs.length) {
  console.log("WGSL compile errors:");
  gpu.compileMsgs.forEach((m) => console.log("  ", m));
}
if (gpu.scopeErr) console.log(`validation scope error: ${gpu.scopeErr}`);

// ── (A) per-sample error vs the validated JS FP64 ECEF reference ──
console.log(
  `\nNear-earth SGP4 GPU vs python-sgp4 (ECEF, budget ${BUDGET_M} m):`,
);
let worst = 0;
let worstName = "";
const perSat = {};
for (let i = 0; i < satrecs.length; i++) {
  const sr = satrecs[i];
  perSat[sr.name] = [];
  for (const tmin of SAMPLE_TIMES) {
    const gpuPos = gpu.perTime[tmin][i];
    const ref = refEcef(sr.ref, sr.s, tmin);
    const dx = gpuPos[0] - ref[0];
    const dy = gpuPos[1] - ref[1];
    const dz = gpuPos[2] - ref[2];
    const errM = Math.sqrt(dx * dx + dy * dy + dz * dz);
    perSat[sr.name].push(errM);
    if (errM > worst) {
      worst = errM;
      worstName = `${sr.name}@${tmin}min`;
    }
  }
  const line = SAMPLE_TIMES.map(
    (t, k) =>
      `${String(t).padStart(5)}m=${perSat[sr.name][k].toFixed(1).padStart(8)}`,
  ).join("  ");
  console.log(`  ${sr.name.padEnd(9)} ${line}  (m)`);
}

// ── (B) deep-space flagged + skipped ──
console.log(`\nDeep-space handling:`);
const gpsSkipped = skipped.find((x) => x.name === "GPS");
for (const x of skipped) {
  console.log(
    `  ${x.name}: flagged deep-space (period ${x.periodMin.toFixed(1)} min >= 225) -> SKIPPED`,
  );
}
const allDeepSkipped = REF.filter((r) => r.deep).every((r) =>
  skipped.some((x) => x.name === r.name),
);
const noNearEarthSkipped = REF.filter((r) => !r.deep).every((r) =>
  satrecs.some((sr) => sr.name === r.name),
);

// ── (D) RENDER + MOVE through the REAL ComputeInstanceCollection ──
// The accuracy check above runs the kernel on a probe-owned device. This
// phase drives the kernel through the SHIPPED engine path (the demo's runtime:
// ComputeInstanceCollection + the seconds-since-epoch time contract +
// instanced vertex-pull draw) to prove the demo renders moving points with no
// console errors — the Principle-8 verification of the demo, not just the math.
await page.goto(`${BASE}/Apps/CesiumViewer/index.html?renderer=webgpu`, {
  waitUntil: "networkidle",
});
await page.waitForFunction(() => !!window.viewer);

// Build seconds-contract params for the near-earth sats (same packing).
const renderParams = [];
for (const sr of satrecs) {
  renderParams.push(...packSgp4Instance(sr.s, [0.0, 1.0, 1.0], 6.0));
}
const render = await page.evaluate(
  async ({ params, fpi, kernel, count }) => {
    const C = await import("/Build/CesiumUnminified/index.js");
    const v = window.viewer;
    const scene = v.scene;
    scene.requestRenderMode = false;
    v.clock.shouldAnimate = false;

    const catalog = scene.primitives.add(
      new C.ComputeInstanceCollection({
        kernel,
        floatsPerInstance: fpi,
        boundingSphere: new C.BoundingSphere(C.Cartesian3.ZERO, 1.0e7),
      }),
    );
    const epoch = C.JulianDate.clone(v.clock.currentTime);
    catalog.epoch = epoch;
    // Re-add each near-earth instance's flat lanes.
    for (let i = 0; i < count; i++) {
      catalog.addInstance(params.slice(i * fpi, (i + 1) * fpi));
    }

    scene.morphTo3D(0);
    v.camera.setView({
      destination: new C.Cartesian3(2.0e7, 0.0, 0.0),
      orientation: {
        direction: new C.Cartesian3(-1.0, 0.0, 0.0),
        up: new C.Cartesian3(0.0, 0.0, 1.0),
      },
    });

    const oncePostRender = () =>
      new Promise((res) => {
        const rm = scene.postRender.addEventListener(() => {
          rm();
          res();
        });
      });
    const renderAt = async (simSeconds) => {
      v.clock.currentTime = C.JulianDate.addSeconds(
        epoch,
        simSeconds,
        new C.JulianDate(),
      );
      await oncePostRender();
      await oncePostRender();
    };
    const grab = () =>
      new Promise((res) => {
        const rm = scene.postRender.addEventListener(() => {
          rm();
          const c = scene.canvas;
          const off = document.createElement("canvas");
          off.width = c.width;
          off.height = c.height;
          const cx = off.getContext("2d");
          cx.drawImage(c, 0, 0);
          res({
            data: cx.getImageData(0, 0, c.width, c.height).data,
            w: c.width,
            h: c.height,
          });
        });
      });
    const isCyan = (d, i) => d[i] < 90 && d[i + 1] > 150 && d[i + 2] > 150;
    const cyanMask = (img) => {
      const mask = new Uint8Array(img.w * img.h);
      let n = 0;
      for (let p = 0; p < mask.length; p++) {
        if (isCyan(img.data, 4 * p)) {
          mask[p] = 1;
          n++;
        }
      }
      return { mask, count: n };
    };

    let f = 0;
    // Warmup (pipeline resolve + first dispatches), 60 s/frame.
    for (; f < 15; f++) await renderAt(f * 60.0);
    const A = cyanMask(await grab());
    // Advance ~45 min more — LEO objects sweep a large arc.
    for (; f < 60; f++) await renderAt(f * 60.0);
    const B = cyanMask(await grab());

    let changed = 0;
    for (let p = 0; p < A.mask.length; p++)
      if (A.mask[p] !== B.mask[p]) changed++;
    return {
      objectCount: catalog.length,
      cyanA: A.count,
      cyanB: B.count,
      changedPct: changed / Math.max(A.count, B.count, 1),
    };
  },
  {
    params: renderParams,
    fpi: SGP4_FLOATS_PER_INSTANCE,
    kernel: SGP4_KERNEL_WGSL,
    count: satrecs.length,
  },
);
console.log(
  `\n(D) render+move via real ComputeInstanceCollection: ${render.objectCount} objects -> cyan px frame15=${render.cyanA} frame60=${render.cyanB}, mask change ${(render.changedPct * 100).toFixed(1)}%`,
);

const aOK = worst < BUDGET_M;
const bOK = allDeepSkipped && noNearEarthSkipped && !!gpsSkipped;
const dOK = render.cyanA > 10 && render.cyanB > 10 && render.changedPct > 0.2;
const cOK =
  (gpu.validationErrors?.length ?? 0) === 0 &&
  errors.length === 0 &&
  (gpu.compileMsgs?.length ?? 0) === 0 &&
  !gpu.scopeErr;

console.log(
  `\n(A) GPU near-earth SGP4 worst error ${worst.toFixed(1)} m < ${BUDGET_M} m (${worstName}) ${aOK ? "OK" : "FAIL"}`,
);
console.log(
  `(B) deep-space flagged+skipped (GPS), near-earth all kept ${bOK ? "OK" : "FAIL"}`,
);
console.log(
  `(C) zero validation/compile/console errors: gpu=${gpu.validationErrors?.length ?? 0} compile=${gpu.compileMsgs?.length ?? 0} page=${errors.length} ${cOK ? "OK" : "FAIL"}`,
);
console.log(
  `(D) demo path renders + moves (cyan ${render.cyanA}/${render.cyanB}, ${(render.changedPct * 100).toFixed(1)}% change, thresh 20%) ${dOK ? "OK" : "FAIL"}`,
);
errors.slice(0, 6).forEach((e) => console.log("  ERR:", e.slice(0, 200)));
gpu.validationErrors
  ?.slice(0, 6)
  .forEach((e) => console.log("  VAL:", e.slice(0, 200)));

const pass = aOK && bOK && cOK && dOK;
console.log(pass ? "\nPASS" : "\nFAIL");
await browser.close();
process.exit(pass ? 0 : 1);
