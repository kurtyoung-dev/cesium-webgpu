// pipeline-cache-invalidation-subscriptions.spec.mjs
// @purpose Proves the two WebGPUContext pipeline-cache lazy getters hold one device-invalidation subscription each across repeated device-loss recoveries instead of stacking a new closure per rebuild.
// @status ACTIVE
//
// WHAT THIS SPEC IS FOR. Both pipeline caches are nulled on device loss and
// rebuilt on the next getter access, so the lazy branch inside each getter runs
// once per recovery. Each run used to call
// `this.onDeviceInvalidated(() => { ... = null; })` with a fresh arrow
// function, and `WebGPUDeviceInvalidationBus.subscribe` is a `Set.add` keyed on
// the callback reference. A new identity every rebuild meant a new Set entry
// every rebuild: one dead closure per recovery, each still invoked on every
// later loss, each holding the Context alive.
//
// The bus's own doc calls subscribe "idempotent over a given callback
// reference", which is exactly the property the getters were not supplying.
//
// HOW IT IS TESTED. The real `WebGPUDeviceInvalidationBus`, the real
// `WebGPUContext` getters, and the real pipeline-cache constructors — nothing
// about the subscription path is re-implemented here. The context instance is
// built with `Object.create(WebGPUContext.prototype)` and given only the fields
// the getters read, which is the pattern `texture-mip-queue-safety.spec.mjs`
// and `perf-manager-teardown.spec.mjs` already use for this class. In
// particular the two unsubscribe fields are NOT primed: they are left absent so
// the getter has to behave correctly on a context whose constructor never ran,
// and so this harness cannot supply the very state the fix depends on.
//
// The observable asserted is the bus's own subscriber count, which is what a
// leak consumes, rather than any private bookkeeping the fix introduced.
//
// Run: node --test Tools/visual-regression/pipeline-cache-invalidation-subscriptions.spec.mjs

import assert from "node:assert/strict";
import fs from "node:fs";
import { registerHooks } from "node:module";
import path from "node:path";
import test from "node:test";
import { fileURLToPath, pathToFileURL } from "node:url";

import ts from "typescript";

import { enableEngineTsResolution } from "./lib/engine-ts-resolver.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const engineWebGPU = path.resolve(
  here,
  "../../packages/engine/Source/Renderer/WebGPU",
);

registerHooks({
  resolve(specifier, context, nextResolve) {
    // Engine shader barrels are generated by the build and are not on disk in
    // a source-only checkout. Nothing on the subscription path reads one.
    if (
      (specifier.startsWith("./") || specifier.startsWith("../")) &&
      specifier.endsWith(".js") &&
      typeof context.parentURL === "string" &&
      context.parentURL.startsWith("file:")
    ) {
      const asJs = new URL(specifier, context.parentURL);
      if (
        asJs.pathname.includes("/packages/engine/Source/Shaders/") &&
        !fs.existsSync(fileURLToPath(asJs))
      ) {
        return {
          url: "data:text/javascript,export default%20%22%22%3B",
          shortCircuit: true,
        };
      }
    }
    return nextResolve(specifier, context);
  },
  load(url, context, nextLoad) {
    if (url.endsWith(".ts")) {
      const source = fs.readFileSync(fileURLToPath(url), "utf8");
      return {
        format: "module",
        source: ts.transpileModule(source, {
          compilerOptions: {
            module: ts.ModuleKind.ESNext,
            target: ts.ScriptTarget.ES2022,
            verbatimModuleSyntax: false,
          },
        }).outputText,
        shortCircuit: true,
      };
    }
    return nextLoad(url, context);
  },
});

